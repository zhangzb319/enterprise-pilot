create index idx_sys_notification_user_read on sys_notification(user_id, is_read);
comment on table sys_notification is '通知表';
comment on column sys_notification.type is '通知类型:MEETING/PROJECT/TASK/SYSTEM';

-- ============================================
-- 模块八:站内私信
-- ============================================

create table chat_message(
    id bigint generated by default as identity primary key,
    sender_id bigint not null,
    receiver_id bigint not null,
    content varchar(2000) not null,
    is_read smallint default 0,
    is_deleted smallint default 0 not null,
    created_at timestamp default current_timestamp,
    constraint fk_msg_sender foreign key (sender_id) references sys_user(id),
    constraint fk_msg_receiver foreign key (receiver_id) references sys_user(id)
);
create index idx_chat_message_sender_receiver on chat_message(sender_id, receiver_id);
create index idx_chat_message_receiver_read on chat_message(receiver_id, is_read);
comment on table chat_message is '站内私信表';

