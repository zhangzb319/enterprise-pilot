create table agent_message(
    id bigint generated by default as identity primary key,
    conversation_id bigint not null,
    role varchar(16) not null,
    content text,
    tool_calls jsonb,
    tool_result jsonb,
    created_at timestamp default current_timestamp,
    constraint fk_msg_conv foreign key (conversation_id) references agent_conversation(id)
);
create index idx_agent_message_conversation_id on agent_message(conversation_id);
comment on table agent_message is 'Agent消息表';
comment on column agent_message.role is 'user/assistant/tool';

-- ============================================
-- 模块五:项目看板
-- ============================================

create table project(
    id bigint generated by default as identity primary key,
    project_name varchar(128) not null,
    description text,
    owner_id bigint not null,
    status smallint default 0,
    progress smallint default 0,
    start_date date,
    end_date date,
    is_deleted smallint default 0 not null,
    created_at timestamp default current_timestamp,
    updated_at timestamp default current_timestamp,
    constraint fk_project_owner foreign key (owner_id) references sys_user(id)
);
create index idx_project_owner_id on project(owner_id);
comment on table project is '项目表';
comment on column project.status is '0草稿 1进行中 2已完成 3已延期';
comment on column project.owner_id is '项目负责人';

create table project_member(
    id bigint generated by default as identity primary key,
    project_id bigint not null,
    user_id bigint not null,
    role_in_project varchar(32) default 'member',
    joined_at timestamp default current_timestamp,
    constraint uk_project_user unique (project_id, user_id),
    constraint fk_pm_project foreign key (project_id) references project(id),
    constraint fk_pm_user foreign key (user_id) references sys_user(id)
);
comment on table project_member is '项目成员关联表';
comment on column project_member.role_in_project is '项目内角色,如leader/member';

create table project_task(
    id bigint generated by default as identity primary key,
    project_id bigint not null,
    title varchar(128) not null,
    description text,
    assignee_id bigint,
    status smallint default 0,
    due_date date,
    created_at timestamp default current_timestamp,
    updated_at timestamp default current_timestamp,
    constraint fk_task_project foreign key (project_id) references project(id),
    constraint fk_task_assignee foreign key (assignee_id) references sys_user(id)
);
create index idx_project_task_project_id on project_task(project_id);
create index idx_project_task_assignee_id on project_task(assignee_id);
comment on table project_task is '项目任务表';
comment on column project_task.status is '0待开始 1进行中 2已完成';

create table project_discussion(
    id bigint generated by default as identity primary key,
    project_id bigint not null,
    user_id bigint not null,
    content text not null,
    parent_id bigint default 0,
    created_at timestamp default current_timestamp,
    is_deleted smallint default 0 not null,
    constraint fk_disc_project foreign key (project_id) references project(id),
    constraint fk_disc_user foreign key (user_id) references sys_user(id)
);
create index idx_project_discussion_project_id on project_discussion(project_id);
create index idx_project_discussion_parent_id on project_discussion(parent_id);
comment on table project_discussion is '项目讨论表';
comment on column project_discussion.parent_id is '父级评论ID,0表示顶级评论';

