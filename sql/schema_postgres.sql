-- ============================================
-- enterprise-pilot 数据库建表脚本(PostgreSQL 版)
-- 说明:按模块分区,在空库中从头执行即可完整建库
-- 用法:psql -U postgres -d enterprise-pilot -f sql/schema_postgres.sql
-- 原 MySQL 版保留于 schema.sql,二者表结构等价
-- ============================================
-- 注意:本脚本假定目标数据库已存在,不执行 create database
-- PostgreSQL 15+ 建库请手工执行:CREATE DATABASE "enterprise-pilot" ENCODING 'UTF8';

-- ============================================
-- 模块一:用户与组织架构
-- ============================================
-- 说明:MySQL 的 tinyint 布尔语义(0/1)在 PG 中用 smallint 保持
-- 与 Java 侧 Integer 字段一一对应,不引入 boolean 避免 JDBC 映射差异

create table sys_user(
    id bigint generated by default as identity primary key,
    employee_no varchar(32) unique,
    dept_id bigint,
    username varchar(64) unique,
    password_hash varchar(128) not null,
    nickname varchar(32),
    real_name varchar(32) not null,
    avatar varchar(255),
    gender smallint check (gender in (0, 1, 2)),
    phone varchar(20) unique,
    email varchar(64) unique,
    position varchar(64),
    status smallint default 1,
    hire_date date,
    leave_date date,
    is_deleted smallint default 0 not null,
    created_at timestamp default current_timestamp,
    updated_at timestamp default current_timestamp
);
create index idx_sys_user_dept_id on sys_user(dept_id);
comment on table sys_user is '用户表';
comment on column sys_user.gender is '0未知 1男 2女';
comment on column sys_user.status is '0待入职 1在职 2离职 3禁用';
comment on column sys_user.password_hash is 'BCrypt加密后的密码';
comment on column sys_user.dept_id is '所属部门,待入职时可为空';

create table sys_department(
    id bigint generated by default as identity primary key,
    dept_name varchar(64) not null,
    parent_id bigint default 0,
    leader_id bigint,
    sort_order int default 0,
    status smallint default 1,
    is_deleted smallint default 0 not null,
    created_at timestamp default current_timestamp,
    updated_at timestamp default current_timestamp,
    constraint fk_dept_leader foreign key (leader_id) references sys_user(id)
);
create index idx_sys_department_parent_id on sys_department(parent_id);
comment on table sys_department is '部门表';
comment on column sys_department.parent_id is '上级部门ID,顶级为0';
comment on column sys_department.status is '0禁用 1正常';

create table sys_role(
    id bigint generated by default as identity primary key,
    role_name varchar(32) not null,
    role_code varchar(32) unique not null,
    description varchar(128),
    status smallint default 1,
    created_at timestamp default current_timestamp,
    updated_at timestamp default current_timestamp
);
comment on table sys_role is '角色表';
comment on column sys_role.role_code is '角色标识,如ROLE_ADMIN';

create table sys_user_role(
    id bigint generated by default as identity primary key,
    user_id bigint not null,
    role_id bigint not null,
    constraint uk_user_role unique (user_id, role_id),
    constraint fk_ur_user foreign key (user_id) references sys_user(id),
    constraint fk_ur_role foreign key (role_id) references sys_role(id)
);
comment on table sys_user_role is '用户角色关联表';

-- ============================================
-- 模块二:会议室预约
-- ============================================

create table meeting_room(
    id bigint generated by default as identity primary key,
    room_name varchar(64) not null unique,
    floor varchar(16),
    capacity int,
    equipment varchar(255),
    status smallint default 1,
    is_deleted smallint default 0 not null,
    created_at timestamp default current_timestamp,
    updated_at timestamp default current_timestamp
);
comment on table meeting_room is '会议室表';
comment on column meeting_room.status is '0停用/维修中 1正常可用';

create table meeting_booking(
    id bigint generated by default as identity primary key,
    room_id bigint not null,
    title varchar(128) not null,
    organizer_id bigint not null,
    start_time timestamp not null,
    end_time timestamp not null,
    status smallint default 1,
    created_at timestamp default current_timestamp,
    updated_at timestamp default current_timestamp,
    constraint fk_booking_room foreign key (room_id) references meeting_room(id),
    constraint fk_booking_organizer foreign key (organizer_id) references sys_user(id)
);
create index idx_meeting_booking_room_time on meeting_booking(room_id, start_time, end_time);
comment on table meeting_booking is '会议室预约表';
comment on column meeting_booking.status is '0已取消 1待开始 2进行中 3已结束';

create table meeting_participant(
    id bigint generated by default as identity primary key,
    booking_id bigint not null,
    user_id bigint not null,
    status smallint default 0,
    created_at timestamp default current_timestamp,
    constraint uk_booking_user unique (booking_id, user_id),
    constraint fk_participant_booking foreign key (booking_id) references meeting_booking(id),
    constraint fk_participant_user foreign key (user_id) references sys_user(id)
);
comment on table meeting_participant is '会议参会人关联表';
comment on column meeting_participant.status is '0待确认 1已接受 2已拒绝';

create table meeting_summary(
    id bigint generated by default as identity primary key,
    booking_id bigint not null unique,
    audio_url varchar(255),
    transcript_text text,
    summary_text text,
    process_status smallint default 0,
    fail_reason varchar(255),
    created_at timestamp default current_timestamp,
    updated_at timestamp default current_timestamp,
    constraint fk_summary_booking foreign key (booking_id) references meeting_booking(id)
);
comment on table meeting_summary is '会议纪要表';
comment on column meeting_summary.transcript_text is 'ASR转写文本';
comment on column meeting_summary.process_status is '0待处理 1转写中 2摘要生成中 3已完成 4失败';

create table meeting_todo(
    id bigint generated by default as identity primary key,
    summary_id bigint not null,
    content varchar(255) not null,
    assignee_id bigint,
    due_date date,
    status smallint default 0,
    created_at timestamp default current_timestamp,
    updated_at timestamp default current_timestamp,
    constraint fk_todo_summary foreign key (summary_id) references meeting_summary(id),
    constraint fk_todo_assignee foreign key (assignee_id) references sys_user(id)
);
comment on table meeting_todo is '会议待办事项表';
comment on column meeting_todo.status is '0待完成 1已完成';

-- ============================================
-- 模块三:RAG知识库
-- ============================================

create table knowledge_doc(
    id bigint generated by default as identity primary key,
    title varchar(128) not null,
    file_url varchar(255) not null,
    file_type varchar(16),
    category varchar(64),
    uploader_id bigint not null,
    process_status smallint default 0,
    chunk_count int default 0,
    fail_reason varchar(255),
    is_deleted smallint default 0 not null,
    created_at timestamp default current_timestamp,
    updated_at timestamp default current_timestamp,
    constraint fk_doc_uploader foreign key (uploader_id) references sys_user(id)
);
create index idx_knowledge_doc_status on knowledge_doc(process_status);
comment on table knowledge_doc is '知识库文档表';
comment on column knowledge_doc.process_status is '0待处理 1处理中 2已入库 3处理失败';

create table knowledge_chunk(
    id bigint generated by default as identity primary key,
    doc_id bigint not null,
    chunk_index int not null,
    content text,
    vector_id varchar(64),
    created_at timestamp default current_timestamp,
    constraint fk_chunk_doc foreign key (doc_id) references knowledge_doc(id)
);
create index idx_knowledge_chunk_doc_id on knowledge_chunk(doc_id);
comment on table knowledge_chunk is '文档分块表';
comment on column knowledge_chunk.vector_id is '对应向量库里的ID';

create table qa_log(
    id bigint generated by default as identity primary key,
    user_id bigint not null,
    question text not null,
    answer text,
    referenced_docs jsonb,
    tools jsonb,
    latency_ms int,
    prompt_tokens int,
    completion_tokens int,
    created_at timestamp default current_timestamp,
    constraint fk_qalog_user foreign key (user_id) references sys_user(id)
);
create index idx_qa_log_user_id on qa_log(user_id);
comment on table qa_log is '问答历史记录表';
comment on column qa_log.referenced_docs is '引用的文档ID列表';
comment on column qa_log.tools is '本次调用过的工具名列表';

